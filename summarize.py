"""Write REPORT.md (cell summaries, status accounting, run status) from the run folders. No model calls.

    uv run experiments/pooled-gamble/summarize.py                  # every grid run under results/
    uv run experiments/pooled-gamble/summarize.py <run dir> ...    # only the named run folders

Statistics use COMPLETED episodes only, the same rule as metrics.py. Truncated, aborted (budget),
error, crashed, and unfinished episodes are counted in their own columns and are never averaged in.
Duplicate records for one episode (a failed attempt later retried) are listed as superseded, with
the record that replaced them. Pilot, mock and multiplier-variant folders are listed but excluded.

REPORT.md contains aggregates only. The exact per-episode table goes to results/episode_table.md,
which is git-ignored with the rest of results/ (raw data is never committed).
"""

from __future__ import annotations

import sys
from pathlib import Path

from records import load_run, select_episodes

HERE = Path(__file__).resolve().parent
RESULTS = HERE / "results"
STATUS_COLS = ("completed", "truncated", "aborted_budget", "error", "crashed")


def fmt(x: float | None, digits: int = 2) -> str:
    return "-" if x is None else f"{x:.{digits}f}"


def mean(xs: list[float]) -> float | None:
    return sum(xs) / len(xs) if xs else None


def main() -> None:
    if len(sys.argv) > 1:
        dirs = [Path(p).resolve() for p in sys.argv[1:]]
    else:
        dirs = sorted(p for p in RESULTS.iterdir() if p.is_dir()) if RESULTS.exists() else []
    runs = [load_run(d) for d in dirs]
    grid = [r for r in runs if r["kind"] == "grid"]
    excluded = [r for r in runs if r["kind"] != "grid"]
    chosen, superseded = select_episodes(grid)
    done = [e for e in chosen if e["status"] == "completed"]

    lines = ["# Pooled gamble: generated report", "",
             "Generated by `summarize.py` (no model calls). Statistics use **completed** episodes only; other "
             "statuses are counted in their own columns. Totals are integer points; the start total is N x 1.", "",
             f"Episode keys (model x condition x N x rep): **{len(chosen)}**; completed **{len(done)}**. "
             f"Superseded records: **{len(superseded)}**. Unresolved (no finished record): "
             f"**{sum(1 for e in chosen if e['status'] not in STATUS_COLS)}**.", "",
             "## Cell summaries", "",
             "| model | condition | n | planned | completed | truncated | aborted (budget) | error | crashed | unresolved "
             "| mean total | mean per agent | ruined agents | mean plays | mean transfers | mean posts | mean invalid "
             "| mean completion tokens | reasoning share | length-limited replies | mean cost USD |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    cells: dict[tuple, list[dict]] = {}
    for e in chosen:
        cells.setdefault((e["key"][0], e["key"][1], e["key"][2]), []).append(e)
    for key in sorted(cells):
        model, cond, n = key
        eps = cells[key]
        ok = [e for e in eps if e["status"] == "completed"]
        count = lambda s: sum(e["status"] == s for e in eps)  # noqa: E731
        unresolved = sum(e["status"] not in STATUS_COLS for e in eps)
        comp_tokens = [e.get("completion_tokens") for e in ok if e.get("completion_tokens") is not None]
        reasoning = [e.get("reasoning_tokens", 0) for e in ok]
        calls = sum(e["calls"] for e in ok) or 0
        share = (sum(reasoning) / sum(comp_tokens)) if comp_tokens and sum(comp_tokens) else None
        length = sum(e.get("length_limited_replies", 0) for e in ok)
        lines.append(
            f"| {model} | {cond} | {n} | {len(eps)} | {count('completed')} | {count('truncated')} "
            f"| {count('aborted_budget')} | {count('error')} | {count('crashed')} | {unresolved} "
            f"| {fmt(mean([e['total_final'] for e in ok]))} | {fmt(mean([e['mean_final'] for e in ok]))} "
            f"| {sum(e['ruined_agents'] for e in ok)} | {fmt(mean([e['plays'] for e in ok]))} "
            f"| {fmt(mean([e['transfers'] for e in ok]))} | {fmt(mean([e['posts'] for e in ok]))} "
            f"| {fmt(mean([e['invalid'] for e in ok]))} "
            f"| {fmt(mean([float(x) for x in comp_tokens]), 0)} | {fmt(share, 3)} | {length}/{calls} "
            f"| {fmt(mean([e['cost_usd'] for e in ok]), 5)} |")

    lines += ["", "## Unfinished or unusable episodes (never averaged)", ""]
    bad = [e for e in chosen if e["status"] not in ("completed",)]
    if bad:
        lines += ["| model | condition | n | rep | status | run | reason |", "|---|---|---|---|---|---|---|"]
        for e in bad:
            reason = (e.get("error") or e.get("reason") or "").replace("|", "/")[:160]
            lines.append(f"| {e['key'][0]} | {e['key'][1]} | {e['key'][2]} | {e['key'][3]} | {e['status']} "
                         f"| {e['run']} | {reason} |")
    else:
        lines.append("None.")

    lines += ["", "## Superseded records (kept, not used)", ""]
    if superseded:
        lines += ["| key | status | run / folder | superseded by |", "|---|---|---|---|"]
        for e in superseded:
            lines.append(f"| {'/'.join(map(str, e['key']))} | {e['status']} | {e['run']} / {e.get('dir') or '-'} "
                         f"| {e['superseded_by']} |")
    else:
        lines.append("None.")

    lines += ["", "## Run folders", "", "| run | kind | records.jsonl | metrics.json | complete | episodes on disk "
              "| incomplete entries | used in analysis |", "|---|---|---|---|---|---|---|---|"]
    for r in runs:
        fin = r["run_finished"]
        complete = "yes" if fin and fin.get("complete") else ("no" if fin else "unknown (no run_finished)")
        lines.append(f"| {r['name']} | {r['kind']} | {'yes' if r['has_records'] else 'no (pre-records run)'} "
                     f"| {'yes' if r['has_metrics'] else 'no'} | {complete} | {len(r['episodes'])} "
                     f"| {len(r['incomplete'])} | {'yes' if r['kind'] == 'grid' else 'no: ' + r['kind']} |")

    out = HERE / "REPORT.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")

    # Exact per-episode values stay out of the committed report (raw-derived), in the ignored results folder.
    table = ["# Per-episode values (git-ignored; generated by summarize.py)", "",
             "| run | model | condition | n | rep | status | turns | final balances | total | plays | transfers "
             "| posts | invalid | calls | cost USD | completion tokens | reasoning tokens | length-limited |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for e in sorted(chosen, key=lambda e: (e["key"][0], e["key"][2], e["key"][3], e["key"][1])):
        if e["status"] == "completed" or e["status"] in ("truncated", "aborted_budget", "error", "crashed"):
            bal = ", ".join(str(v) for v in (e.get("final_balances") or {}).values())
            table.append(f"| {e['run']} | {e['key'][0]} | {e['key'][1]} | {e['key'][2]} | {e['key'][3]} | {e['status']} "
                         f"| {e.get('turns', '-')} | {bal} | {e.get('total_final', '-')} | {e.get('plays', '-')} "
                         f"| {e.get('transfers', '-')} | {e.get('posts', '-')} | {e.get('invalid', '-')} "
                         f"| {e.get('calls', '-')} | {e.get('cost_usd', 0):.6f} | {e.get('completion_tokens', '-')} "
                         f"| {e.get('reasoning_tokens', '-')} | {e.get('length_limited_replies', '-')} |")
    (RESULTS / "episode_table.md").write_text("\n".join(table) + "\n", encoding="utf-8")
    print(f"wrote {out}: {len(done)} completed of {len(chosen)} episode keys; "
          f"{len(superseded)} superseded; {len(excluded)} non-grid folder(s) excluded")
    print(f"wrote {RESULTS / 'episode_table.md'} (git-ignored)")


if __name__ == "__main__":
    main()
